//! `catalog/registry.lock`: the permanent record of what each tweak number means.
//!
//! Each line is `component number id rev hash`. Entries are never removed or changed. A released
//! number keeps its meaning forever, and each revision's hash proves its resources didn't change,
//! which is what lets a future version undo a change an older version made.

use std::collections::{BTreeMap, BTreeSet};

use sha2::{Digest, Sha256};

use crate::schema::{Revision, Tweak};

#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct LockEntry {
    pub component: String,
    pub number: u32,
    pub id: String,
    pub rev: u32,
    pub hash: String,
}

/// A hash of what a revision changes. It uses parsed values, so formatting edits don't alter it.
pub fn revision_hash(rev: &Revision) -> Result<String, serde_json::Error> {
    let canonical = serde_json::to_string(&rev.resource)?;
    let digest = Sha256::digest(canonical.as_bytes());
    Ok(digest.iter().map(|b| format!("{b:02x}")).collect())
}

/// Parses lock file text. Blank lines and `#` comments are ignored.
pub fn parse_lock(text: &str) -> Result<Vec<LockEntry>, String> {
    let mut entries = Vec::new();
    for (i, line) in text.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let parts: Vec<&str> = line.split_whitespace().collect();
        let [component, number, id, rev, hash] = parts[..] else {
            return Err(format!("line {}: expected 5 fields: {line}", i + 1));
        };
        let number = number
            .parse()
            .map_err(|_| format!("line {}: bad number {number}", i + 1))?;
        let rev = rev
            .parse()
            .map_err(|_| format!("line {}: bad revision {rev}", i + 1))?;
        entries.push(LockEntry {
            component: component.to_string(),
            number,
            id: id.to_string(),
            rev,
            hash: hash.to_string(),
        });
    }
    Ok(entries)
}

/// Renders entries sorted by component, number and revision.
pub fn render_lock(entries: &[LockEntry]) -> String {
    let mut sorted = entries.to_vec();
    sorted.sort();
    let mut out = String::from(
        "# Generated by `cargo xtask update-lock`. Entries are permanent: never edit or remove one.\n",
    );
    for e in sorted {
        out.push_str(&format!(
            "{} {} {} {} {}\n",
            e.component, e.number, e.id, e.rev, e.hash
        ));
    }
    out
}

/// The entries a catalog implies, one per revision.
pub fn entries_from_catalog(tweaks: &[Tweak]) -> Result<Vec<LockEntry>, serde_json::Error> {
    let mut entries = Vec::new();
    for t in tweaks {
        for rev in &t.rev {
            entries.push(LockEntry {
                component: t.component.as_str().to_string(),
                number: t.number,
                id: t.id.clone(),
                rev: rev.rev,
                hash: revision_hash(rev)?,
            });
        }
    }
    Ok(entries)
}

/// Checks the lock and the catalog describe exactly the same tweaks.
pub fn check_lock_matches_catalog(lock: &[LockEntry], catalog: &[LockEntry]) -> Vec<String> {
    let lock_set: BTreeSet<&LockEntry> = lock.iter().collect();
    let catalog_set: BTreeSet<&LockEntry> = catalog.iter().collect();
    let mut problems = Vec::new();
    for e in catalog_set.difference(&lock_set) {
        problems.push(format!(
            "{} rev {} ({}#{}) isn't in the lock, or its resources changed. A changed tweak needs a \
             new revision. For a new tweak or revision run `cargo xtask update-lock`",
            e.id, e.rev, e.component, e.number
        ));
    }
    for e in lock_set.difference(&catalog_set) {
        problems.push(format!(
            "{} rev {} ({}#{}) is in the lock but not the catalog. Tweaks are never deleted: mark \
             them retired instead",
            e.id, e.rev, e.component, e.number
        ));
    }
    problems
}

/// Checks a newer lock against an older one: nothing removed or changed, and new numbers are next in
/// line for their component.
pub fn check_append_only(old: &[LockEntry], new: &[LockEntry]) -> Vec<String> {
    let mut problems = Vec::new();
    let new_set: BTreeSet<&LockEntry> = new.iter().collect();
    for e in old {
        if !new_set.contains(e) {
            problems.push(format!(
                "{} rev {} ({}#{}) was removed or changed",
                e.id, e.rev, e.component, e.number
            ));
        }
    }

    let mut id_of_number: BTreeMap<(&str, u32), &str> = BTreeMap::new();
    let mut number_of_id: BTreeMap<&str, (&str, u32)> = BTreeMap::new();
    for e in old {
        id_of_number.insert((&e.component, e.number), &e.id);
        number_of_id.insert(&e.id, (&e.component, e.number));
    }
    let mut next_number: BTreeMap<&str, u32> = BTreeMap::new();
    for e in old {
        let next = next_number.entry(&e.component).or_insert(1);
        *next = (*next).max(e.number + 1);
    }

    let mut added: Vec<&LockEntry> = new.iter().filter(|e| !old.contains(e)).collect();
    added.sort();
    for e in added {
        if let Some(&(component, number)) = number_of_id.get(e.id.as_str()) {
            if component != e.component || number != e.number {
                problems.push(format!(
                    "{} moved from {component}#{number} to {}#{}. Retire it and add a new tweak",
                    e.id, e.component, e.number
                ));
            }
            continue;
        }
        if let Some(existing) = id_of_number.get(&(e.component.as_str(), e.number)) {
            problems.push(format!(
                "{}#{} already means {existing}, so {} can't reuse it",
                e.component, e.number, e.id
            ));
            continue;
        }
        let next = next_number.entry(&e.component).or_insert(1);
        if e.number != *next {
            problems.push(format!(
                "{} takes {}#{}, but the next free number is {}",
                e.id, e.component, e.number, next
            ));
        }
        *next = (*next).max(e.number + 1);
        id_of_number.insert((&e.component, e.number), &e.id);
        number_of_id.insert(&e.id, (&e.component, e.number));
    }
    problems
}
