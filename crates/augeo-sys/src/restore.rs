mod tests {
    use super::*;

    #[test]
    fn creating_reports_what_really_happened() {
        match create("augeo test").unwrap() {
            RestorePoint::Created { sequence } => assert!(sequence > 0),
            RestorePoint::SkippedRecentExists { .. } | RestorePoint::ProtectionOff => {}
        }
    }
}
