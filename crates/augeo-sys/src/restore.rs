//! System Restore points. These are a safety net only: augeo's undo never depends on them.
//!
//! `SRSetRestorePoint` reports success even when Windows silently skips creating a point because one
//! was made in the last 24 hours, returning the old sequence number. So this compares sequence
//! numbers and reports what actually happened. All of it needs elevation.

use augeo_ports::PortError;
use windows::{
    Win32::{
        Foundation::{HMODULE, RPC_E_TOO_LATE},
        Security::PSECURITY_DESCRIPTOR,
        System::{
            Com::{
                CLSCTX_INPROC_SERVER, COINIT_MULTITHREADED, CoCreateInstance, CoInitializeEx,
                CoInitializeSecurity, CoSetProxyBlanket, CoUninitialize, EOAC_NONE,
                RPC_C_AUTHN_LEVEL_CALL, RPC_C_AUTHN_LEVEL_DEFAULT, RPC_C_IMP_LEVEL_IMPERSONATE,
            },
            LibraryLoader::{GetProcAddress, LOAD_LIBRARY_SEARCH_SYSTEM32, LoadLibraryExW},
            Restore::{
                BEGIN_SYSTEM_CHANGE, END_SYSTEM_CHANGE, MODIFY_SETTINGS, RESTOREPOINTINFOW,
                STATEMGRSTATUS,
            },
            Rpc::{RPC_C_AUTHN_WINNT, RPC_C_AUTHZ_NONE},
            Variant::VARIANT,
            Wmi::{
                IWbemLocator, IWbemServices, WBEM_FLAG_FORWARD_ONLY, WBEM_FLAG_RETURN_IMMEDIATELY,
                WBEM_INFINITE, WbemLocator,
            },
        },
    },
    core::{BOOL, BSTR, HSTRING, PCWSTR, s, w},
};

const ERROR_SERVICE_DISABLED: u32 = 1058;

/// What creating a restore point actually did.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RestorePoint {
    Created {
        sequence: i64,
    },
    /// Windows skipped it because a recent one exists, while reporting success.
    SkippedRecentExists {
        existing_sequence: i64,
    },
    /// System Protection is off for this drive.
    ProtectionOff,
}

/// Initializes COM for the current thread and undoes it when dropped.
struct Com;

impl Com {
    fn init() -> Result<Self, PortError> {
        // SAFETY: the pointer argument is reserved and must be None.
        unsafe { CoInitializeEx(None, COINIT_MULTITHREADED) }
            .ok()
            .map_err(|e| PortError::Failed(format!("starting COM: {e}")))?;
        // SAFETY: all arguments are documented defaults for "use this process's identity".
        let result = unsafe {
            CoInitializeSecurity(
                Some(PSECURITY_DESCRIPTOR::default()),
                -1,
                None,
                None,
                RPC_C_AUTHN_LEVEL_DEFAULT,
                RPC_C_IMP_LEVEL_IMPERSONATE,
                None,
                EOAC_NONE,
                None,
            )
        };
        match result {
            // Already set earlier in this process, which is fine.
            Err(e) if e.code() != RPC_E_TOO_LATE => {
                Err(PortError::Failed(format!("setting COM security: {e}")))
            }
            _ => Ok(Self),
        }
    }
}

impl Drop for Com {
    fn drop(&mut self) {
        // SAFETY: this balances the successful CoInitializeEx in `init`, on the same thread.
        unsafe { CoUninitialize() };
    }
}

fn wmi_failed(context: &str, e: &windows::core::Error) -> PortError {
    PortError::Failed(format!("{context}: {e}"))
}

fn restore_namespace() -> Result<IWbemServices, PortError> {
    let context = "connecting to System Restore";
    // SAFETY: the class ID and interface match, as generated by the windows crate.
    let locator: IWbemLocator =
        unsafe { CoCreateInstance(&WbemLocator, None, CLSCTX_INPROC_SERVER) }
            .map_err(|e| wmi_failed(context, &e))?;
    let empty = BSTR::new();
    // SAFETY: the strings outlive the call, and empty credentials mean "the current user".
    let services = unsafe {
        locator.ConnectServer(
            &BSTR::from("ROOT\\DEFAULT"),
            &empty,
            &empty,
            &empty,
            0,
            &empty,
            None,
        )
    }
    .map_err(|e| wmi_failed(context, &e))?;
    // SAFETY: the proxy is the interface just returned, and the rest are documented constants.
    unsafe {
        CoSetProxyBlanket(
            &services,
            RPC_C_AUTHN_WINNT,
            RPC_C_AUTHZ_NONE,
            PCWSTR::null(),
            RPC_C_AUTHN_LEVEL_CALL,
            RPC_C_IMP_LEVEL_IMPERSONATE,
            None,
            EOAC_NONE,
        )
    }
    .map_err(|e| wmi_failed(context, &e))?;
    Ok(services)
}

fn latest_sequence(services: &IWbemServices) -> Result<Option<i64>, PortError> {
    let context = "listing restore points";
    // SAFETY: the strings outlive the call.
    let rows = unsafe {
        services.ExecQuery(
            &BSTR::from("WQL"),
            &BSTR::from("SELECT SequenceNumber FROM SystemRestore"),
            WBEM_FLAG_FORWARD_ONLY | WBEM_FLAG_RETURN_IMMEDIATELY,
            None,
        )
    }
    .map_err(|e| wmi_failed(context, &e))?;

    let mut latest = None;
    loop {
        let mut row = [None];
        let mut returned = 0u32;
        // SAFETY: the array and count outlive the call.
        let status = unsafe { rows.Next(WBEM_INFINITE, &mut row, &mut returned) };
        if returned == 0 {
            status.ok().map_err(|e| wmi_failed(context, &e))?;
            return Ok(latest);
        }
        let Some(object) = row[0].take() else {
            return Ok(latest);
        };
        let mut value = VARIANT::default();
        // SAFETY: the name is a valid constant, and `value` is a valid place for the result.
        unsafe { object.Get(w!("SequenceNumber"), 0, &mut value, None, None) }
            .map_err(|e| wmi_failed(context, &e))?;
        let sequence = i64::from(
            i32::try_from(&value).map_err(|e| wmi_failed("reading a sequence number", &e))?,
        );
        latest = latest.max(Some(sequence));
    }
}

type SrSetRestorePointW =
    unsafe extern "system" fn(*const RESTOREPOINTINFOW, *mut STATEMGRSTATUS) -> BOOL;

fn sr_function() -> Result<SrSetRestorePointW, PortError> {
    let name = HSTRING::from("srclient.dll");
    // SAFETY: the name outlives the call, and the search is limited to System32. It's loaded at run
    // time because some editions of Windows don't have it, which mustn't stop augeo from starting.
    let module: HMODULE = unsafe { LoadLibraryExW(&name, None, LOAD_LIBRARY_SEARCH_SYSTEM32) }
        .map_err(|e| {
            PortError::NotAvailable(format!("System Restore isn't available here: {e}"))
        })?;
    // SAFETY: the module just loaded, and the name is a valid constant.
    let function = unsafe { GetProcAddress(module, s!("SRSetRestorePointW")) }
        .ok_or_else(|| PortError::NotAvailable("srclient.dll has no SRSetRestorePointW".into()))?;
    // SAFETY: this signature is the one documented for SRSetRestorePointW.
    Ok(unsafe {
        std::mem::transmute::<unsafe extern "system" fn() -> isize, SrSetRestorePointW>(function)
    })
}

fn description_field(text: &str) -> [u16; 256] {
    let mut out = [0u16; 256];
    for (slot, unit) in out.iter_mut().take(255).zip(text.encode_utf16()) {
        *slot = unit;
    }
    out
}

/// Creates a restore point, and reports whether Windows really did.
pub fn create(description: &str) -> Result<RestorePoint, PortError> {
    let _com = Com::init()?;
    let services = restore_namespace()?;
    let before = latest_sequence(&services)?;
    let function = sr_function()?;

    let mut info = RESTOREPOINTINFOW {
        dwEventType: BEGIN_SYSTEM_CHANGE,
        dwRestorePtType: MODIFY_SETTINGS,
        llSequenceNumber: 0,
        szDescription: description_field(description),
    };
    let mut status = STATEMGRSTATUS::default();
    // SAFETY: both structures outlive the call and have the layouts the API documents.
    let ok = unsafe { function(&info, &mut status) };
    if !ok.as_bool() {
        let code = status.nStatus.0;
        if code == ERROR_SERVICE_DISABLED {
            return Ok(RestorePoint::ProtectionOff);
        }
        return Err(PortError::Failed(format!(
            "creating a restore point failed with error {code}"
        )));
    }
    let sequence = status.llSequenceNumber;

    info.dwEventType = END_SYSTEM_CHANGE;
    info.llSequenceNumber = sequence;
    // SAFETY: as above.
    let ok = unsafe { function(&info, &mut status) };
    if !ok.as_bool() {
        let code = status.nStatus.0;
        return Err(PortError::Failed(format!(
            "finishing a restore point failed with error {code}"
        )));
    }

    // The API can't be trusted to say whether it did anything, so look.
    let after = latest_sequence(&services)?;
    Ok(if after > before {
        RestorePoint::Created {
            sequence: after.unwrap_or(sequence),
        }
    } else {
        RestorePoint::SkippedRecentExists {
            existing_sequence: after.unwrap_or(sequence),
        }
    })
}

/// Turns on System Protection for a drive such as `C:\`. This changes a system setting, so it must
/// only happen after asking.
pub fn enable_protection(drive: &str) -> Result<(), PortError> {
    let context = "turning on System Protection";
    let _com = Com::init()?;
    let services = restore_namespace()?;
    let class_name = BSTR::from("SystemRestore");
    let mut class = None;
    // SAFETY: the name outlives the call, and `class` is a valid place for the result.
    unsafe {
        services.GetObject(
            &class_name,
            Default::default(),
            None,
            Some(&mut class),
            None,
        )
    }
    .map_err(|e| wmi_failed(context, &e))?;
    let class = class.ok_or_else(|| PortError::Failed(format!("{context}: no such class")))?;

    let mut parameters = None;
    // SAFETY: the name is a valid constant, and `parameters` is a valid place for the result.
    unsafe { class.GetMethod(w!("Enable"), 0, &mut parameters, std::ptr::null_mut()) }
        .map_err(|e| wmi_failed(context, &e))?;
    let parameters =
        parameters.ok_or_else(|| PortError::Failed(format!("{context}: no parameters")))?;
    // SAFETY: the class object is valid.
    let input = unsafe { parameters.SpawnInstance(0) }.map_err(|e| wmi_failed(context, &e))?;
    let drive_value = VARIANT::from(BSTR::from(drive));
    // SAFETY: the name and value outlive the call.
    unsafe { input.Put(w!("Drive"), 0, &drive_value, 0) }.map_err(|e| wmi_failed(context, &e))?;
    // SAFETY: the strings and input outlive the call.
    unsafe {
        services.ExecMethod(
            &class_name,
            &BSTR::from("Enable"),
            Default::default(),
            None,
            &input,
            None,
            None,
        )
    }
    .map_err(|e| wmi_failed(context, &e))
}

